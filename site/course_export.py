# ---------------------------------------------------------------------------------------------- hub
def hub_page(mods: list[Module], lessons: dict) -> str:
    paths_md = (ROOT / "docs/learning-paths/README.md").read_text(encoding="utf-8")
    paths = absolute(re.search(r"\| Path \| For \| Time \| Finish line \|[\s\S]*?(?=\n\n)", paths_md).group(0), "docs/learning-paths/")
