# ------------------------------------------------------------------------------------------ helpers
def strip_emoji(s: str) -> str:
    return re.sub(r"^[^\w\[]+", "", s).strip()


def page_name(title: str) -> str:
    """'🔁 Module 05 · The Agent Loop: No Framework to Strands' -> 'Module-05-The-Agent-Loop-No-Framework-to-Strands'."""
    t = strip_emoji(title)
    t = re.sub(r"[^A-Za-z0-9]+", "-", t).strip("-")
    return t


def sections(md: str) -> tuple[str, dict[str, str]]:
    """The text before the first ``## `` heading, and each ``## `` section's body, in order."""
    parts = re.split(r"^## (.+)$", md, flags=re.M)
    head, rest = parts[0], parts[1:]
    body = {}
    for i in range(0, len(rest), 2):
        body[rest[i].strip()] = rest[i + 1].strip("\n")
    return head, body


def absolute(md: str, base: str) -> str:
    """Rewrite every relative link in ``md`` to the repository, with blob for files and tree for folders."""
    def one(m: re.Match) -> str:
        text, href = m.group(1), m.group(2)
        if href.startswith(("http://", "https://", "mailto:", "#")):
            return m.group(0)
        path, _, frag = href.partition("#")
        full = posixpath.normpath(posixpath.join(base, path)) if path else base.rstrip("/")
        target = ROOT / full
        kind = TREE if target.is_dir() or path.endswith("/") else BLOB
        return f"[{text}]({kind}{full}{'#' + frag if frag else ''})"
    return re.sub(r"\[([^\]]*)\]\(([^)\s]+)\)", one, md)


def wiki_link(page: str, text: str) -> str:
    return f"[{text}]({page})"


def write(path: Path, text: str) -> None:
    if path.exists() and not path.read_text(encoding="utf-8").startswith(MARK):
        sys.exit(f"refusing to overwrite hand-written wiki page {path.name}")
    path.write_text(text, encoding="utf-8")


def put_block(path: Path, block: str, after: str) -> None:
    text = path.read_text(encoding="utf-8")
    if BLOCK.search(text):
        text = BLOCK.sub(block, text, count=1)
    elif after in text:
        i = text.index(after) + len(after)
        text = text[:i] + "\n\n" + block + text[i:].lstrip("\n")
    else:
        sys.exit(f"{path.name}: no course block and no '{after}' to put one after")
    path.write_text(text, encoding="utf-8")


# ------------------------------------------------------------------------------------------ modules
class Module:
    def __init__(self, d: Path):
        self.dir = d
        self.num = d.name[:2]
        md = (d / "README.md").read_text(encoding="utf-8")
        self.title = re.search(r"^# (.+)$", md, re.M).group(1).strip()
        self.name = strip_emoji(self.title).split("·", 1)[1].strip()       # after "Module NN ·"
        self.page = page_name(self.title)
        head, self.secs = sections(md)
        m = re.search(r"^> (.+)$", head, re.M)
        self.tagline = m.group(1).strip() if m else ""
        m = re.search(r"\*\*Estimated time:\*\* (.+?) &nbsp;·&nbsp; \*\*Prerequisites:\*\* (.+)$", head, re.M)
        self.time, self.prereq = (m.group(1).strip(), m.group(2).strip()) if m else ("", "")
        # the paragraph(s) between the meta line and the rule
        intro = head[m.end():] if m else head
        intro = intro.split("\n---", 1)[0]
        self.intro = "\n".join(l for l in intro.strip().splitlines() if not l.startswith("<")).strip()
        self.base = f"modules/{d.name}/"
        self.track = next(name for name, lo, hi in TRACKS if lo <= self.num <= hi)

    def section(self, name: str) -> str:
        return absolute(self.secs.get(name, ""), self.base)


def load_modules() -> list[Module]:
    return [Module(d) for d in sorted(MODULES.iterdir()) if d.is_dir() and re.match(r"\d\d-", d.name)]


def module_page(m: Module, mods: list[Module], lessons: dict) -> str:
    k = mods.index(m)
    prev = mods[k - 1] if k else None
    nxt = mods[k + 1] if k + 1 < len(mods) else None
    slug, why, tool, tool_name = FRAME[m.num]
    les = lessons[slug]
    play = f" Then try **[{tool_name}]({SIM}#/{tool})** in the playbook: the same decision, with your numbers." if tool else ""
