def sidebar_block(mods: list[Module]) -> str:
    items = "\n".join(f"{m.num}. [{m.name}]({m.page})" for m in mods)
    return ("<!-- course:start · generated by site/course_export.py -->\n"
            "**[The course companion](Course-Companion)** · **[Labs](Labs-Companion)**\n\n"
            f"<details><summary><b>The {len(mods)} modules</b></summary>\n\n{items}\n\n</details>\n"
            "<!-- course:end -->\n")


def main() -> int:
    _, tracks, lessons = learn.load()
    mods = load_modules()
    bad = [f"{n}: {s}" for n, (s, *_) in FRAME.items() if s not in lessons]
    if bad:
        sys.exit("FRAME names lessons that do not exist: " + ", ".join(bad))
    missing = [m.num for m in mods if m.num not in FRAME]
    if missing:
        sys.exit("FRAME has no entry for module(s) " + ", ".join(missing))
    for m in mods:
        for want in ("What you will be able to do", "Concepts in this module", "Run it in this order", "Solutions", "Common mistakes"):
            if want not in m.secs:
                sys.exit(f"{m.dir.name}/README.md has no '## {want}' section")
    written = []
    for m in mods:
        write(WIKI / f"{m.page}.md", module_page(m, mods, lessons))
        written.append(m.page)
    write(WIKI / "Course-Companion.md", hub_page(mods, lessons))
    write(WIKI / "Labs-Companion.md", labs_page(mods))
    written += ["Course-Companion", "Labs-Companion"]
    put_block(WIKI / "_Sidebar.md", sidebar_block(mods), after="### 📚 Course and labs")
    stale = [p for p in WIKI.glob("*.md") if p.stem not in written and p.read_text(encoding="utf-8").startswith(MARK)]
    for p in stale:
        p.unlink()
    print(f"wrote {len(written)} wiki pages; sidebar course block updated; {len(stale)} stale generated pages deleted")
    for p in stale:
        print(f"  deleted wiki/{p.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
